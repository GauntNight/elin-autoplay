"""Generate tools/README.md from every tool's module docstring (the review of 2026-10-30, the user's yes:
elin-play's tool table had become a changelog at the skill's 350-line cap; a tool's purpose and usage live
with the tool, and the skill names the rule). One entry a tool: the docstring's first paragraph and its
usage lines. hygiene.py says when the README is older than a tool or a tool has no docstring.

usage: python -I tools/toolindex.py [--check]
  --check  exit 1 when README.md would change (nothing written)
"""
import ast
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
README = TOOLS / "README.md"
SKIP = {"__init__.py", "toolindex.py"}


def entry(path):
    try:
        mod = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError as e:
        return f"- `{path.name}`: (syntax error: {e})"
    doc = ast.get_docstring(mod) or ""
    if not doc.strip():
        return f"- `{path.name}`: (no docstring)"
    lines = doc.strip().splitlines()
    first = []
    for ln in lines:
        if not ln.strip():
            break
        first.append(ln.strip())
    usage = []
    grab = False
    for ln in lines:
        if ln.lstrip().lower().startswith("usage:"):
            grab = True
        if grab:
            if not ln.strip():
                break
            usage.append("    " + ln.rstrip())
    out = f"- **`{path.name}`**: " + " ".join(first)
    if usage:
        out += "\n" + "\n".join(usage)
    return out


def render():
    paths = sorted(p for p in TOOLS.glob("*.py") if p.name not in SKIP)
    body = "\n".join(entry(p) for p in paths)
    return ("# The tools (generated by `python -I tools/toolindex.py` from each tool's docstring: edit the docstring, not this file)\n\n"
            "Shared rules are in `.claude/skills/elin-play/SKILL.md` (the thresholds, the hard rules); what each tool's domain taught us is in\n"
            "`knowledge/tool-notes.md`. Every tool: exit 0 done, 1 refused, 2 the bridge, 3 stopped for a decision.\n\n" + body + "\n")


def main():
    text = render()
    if "--check" in sys.argv:
        cur = README.read_text(encoding="utf-8") if README.exists() else ""
        if cur != text:
            print("tools/README.md is out of date: python -I tools/toolindex.py")
            sys.exit(1)
        print("tools/README.md is current")
        return
    README.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {README} ({len(text.splitlines())} lines, {sum(1 for ln in text.splitlines() if ln.startswith('- '))} tools)")


if __name__ == "__main__":
    main()
